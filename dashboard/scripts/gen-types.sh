#!/usr/bin/env bash
# Regenerates src/lib/database.types.ts from the schema in supabase/migrations.
# DATABASE_URL must point at a Postgres with supabase/tests/ci_bootstrap.sql and
# every migration applied (CI does this; locally any throwaway Postgres works).
set -euo pipefail
: "${DATABASE_URL:?set DATABASE_URL to a Postgres with the migrations applied}"
cd "$(dirname "$0")/.."
out=src/lib/database.types.ts
{
  echo "// Generated by \`npm run gen:types\` from supabase/migrations. Do not edit."
  npx supabase gen types typescript --db-url "$DATABASE_URL" --schema public
} > "$out.tmp"
mv "$out.tmp" "$out"
echo "wrote $out"
